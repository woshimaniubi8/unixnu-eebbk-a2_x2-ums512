#!/usr/bin/env python3
"""Emit the original 1h190 DOWNLOAD_INI sections from its packed wifi_conf_t."""
import argparse
import hashlib
from pathlib import Path
import struct

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('input', type=Path)
parser.add_argument('output', type=Path)
args = parser.parse_args()
data = args.input.read_bytes()
expected = '5b91206f79606e65780da3a229584bf8c3e2beb19b7a2437345688cfe5621fff'
assert len(data) == 3300 and hashlib.sha256(data).hexdigest() == expected
assert struct.unpack_from('<I', data, 1792)[0] == 0
sections = [(1, data[:328]), (2, data[328:1792]), (4, data[3296:3299])]
lines = ['// SPDX-License-Identifier: GPL-2.0-only',
         '// Generated by scripts/generate-sprd-wifi-config.py. Do not edit.',
         '// Original sprdwl_ng.ko wifi_conf_t: sec1=328, sec2=1464, wifi_param@3296.',
         '#pragma once', '#include <stdint.h>', 'namespace SprdWcn {']
for section, body in sections:
    lines.append(f'constexpr uint8_t kFactoryWifiSection{section}[{len(body)}]={{')
    lines.extend('    '+','.join(f'0x{b:02x}' for b in body[at:at+16])+',' for at in range(0, len(body), 16))
    lines.append('};')
lines.append('}')
args.output.write_bytes(('\n'.join(lines)+'\n').encode('utf8'))
print('Generated factory sections 1/2/4; sizes 328/1464/3; no RF section3 in this input.')
