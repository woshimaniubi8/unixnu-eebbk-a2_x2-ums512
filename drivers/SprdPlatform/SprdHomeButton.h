#pragma once

#include <stdint.h>

namespace SprdKeys {
// Consumer report 2: Menu (Home), Power, Volume Increment, Volume Decrement.
constexpr uint8_t Home = 1u << 0;
constexpr uint8_t Power = 1u << 1;
constexpr uint8_t VolumeUp = 1u << 2;
constexpr uint8_t VolumeDown = 1u << 3;
constexpr uint8_t PhysicalMask = Power | VolumeUp | VolumeDown;
constexpr uint8_t ReportMask = PhysicalMask | Home;
constexpr uint8_t ConsumerReportId = 2;

class VolumeHome {
public:
    static constexpr uint64_t HoldMs = 800;
    static constexpr uint64_t PulseMs = 70;
    static constexpr uint64_t MaxSampleGapMs = 250;

    uint8_t sample(uint8_t raw, uint8_t stable, uint64_t nowMs) {
        raw &= PhysicalMask;
        stable &= PhysicalMask;
        if (haveSample_ && (nowMs < lastSample_ || nowMs - lastSample_ > MaxSampleGapMs)) {
            cancelHold();
            pulse_ = 0;
        }
        lastSample_ = nowMs;
        haveSample_ = true;

        if ((raw | stable) & (Power | VolumeUp)) {
            // Preserve native combinations, and never reinterpret the tail of
            // a power/recovery chord as a fresh VolumeDown hold.
            cancelHold();
            pulse_ = 0;
            return report(stable, nowMs);
        }
        if (raw | stable) {
            if (armed_ && !tracking_ && raw == VolumeDown && stable == VolumeDown) {
                tracking_ = true;
                started_ = nowMs;
                pulse_ = 0; // Separate a new tap from a preceding report.
            }
            return report(armed_ ? 0 : stable, nowMs);
        }

        // Commit only on a debounced release, never from a held/stuck key at
        // boot. Release the HID bit after a bounded pulse, even on a read miss.
        if (tracking_) {
            pulse_ = nowMs - started_ >= HoldMs ? Home : VolumeDown;
            pulseStarted_ = nowMs;
        }
        tracking_ = false;
        armed_ = true;
        return report(0, nowMs);
    }

    uint8_t missed(uint64_t nowMs) {
        // Missing samples cannot qualify a long press. Preserve the last
        // physical report but still expire a report generated by this mapper.
        cancelHold();
        return report(physical_, nowMs);
    }

private:
    void cancelHold() {
        tracking_ = false;
        armed_ = false;
    }

    uint8_t report(uint8_t physical, uint64_t nowMs) {
        physical_ = physical;
        if (pulse_ && (nowMs < pulseStarted_ || nowMs - pulseStarted_ >= PulseMs)) {
            pulse_ = 0;
        }
        return physical_ | pulse_;
    }

    bool armed_ = false;
    bool tracking_ = false;
    bool haveSample_ = false;
    uint64_t started_ = 0;
    uint64_t lastSample_ = 0;
    uint64_t pulseStarted_ = 0;
    uint8_t physical_ = 0;
    uint8_t pulse_ = 0;
};
}
